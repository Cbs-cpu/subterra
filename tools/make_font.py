def accented(base, mark, caps):
    """Letra base con una marca (skeleton de una fila) encima."""
    rows, top, bold = G[base]
    w = max(len(r) for r in rows)
    m = mark.ljust(w, ".")[:w] if len(mark) <= w else mark[:w]
    if caps:
        return ([m] + rows, -1, bold)
    # minúsculas: la marca va en la fila 0 y la letra empieza en la 2
    return ([m, "." * w] + rows, 0, bold)


ACUTE = {4: "..#.", 3: "..#", 1: "#", 2: ".#"}
for b, a in [("A", "Á"), ("E", "É"), ("I", "Í"), ("O", "Ó"), ("U", "Ú")]:
    w = len(G[b][0][0])
    G[a] = accented(b, ACUTE.get(w, "..#."), True)
for b, a in [("A", "À"), ("E", "È")]:
    G[a] = accented(b, ".#..", True)
G["Ü"] = accented("U", "#..#", True)
G["Ñ"] = accented("N", ".####.", True)
for b, a in [("a", "á"), ("e", "é"), ("o", "ó"), ("u", "ú")]:
    G[a] = accented(b, "..#.", False)
G["í"] = (["..#", "...", ".#.", ".#.", ".#.", ".#.", ".#."], 0, True)
G["ñ"] = accented("n", ".##.", False)
G["ü"] = accented("u", "#..#", False)


def bolden(rows):
    out = []
    for r in rows:
        w = len(r) + 1
        s = ["."] * w
        for x, c in enumerate(r):
            if c == "#":
                s[x] = "#"
                s[x + 1] = "#"
        out.append("".join(s))
    return out


def build():
    order = [".notdef", "space"]
    cmap = {32: "space"}
    glyphs = {}
    metrics = {}

    pen = TTGlyphPen(None)
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (6 * PX, 0)
    pen = TTGlyphPen(None)
    glyphs["space"] = pen.glyph()
    metrics["space"] = (4 * PX, 0)

    for ch, (rows, top, bold) in G.items():
        if bold:
            rows = bolden(rows)
        name = "uni%04X" % ord(ch)
        pen = TTGlyphPen(None)
        w = max(len(r) for r in rows)
        for i, r in enumerate(rows):
            row = top + i
            y0 = (6 - row) * PX
            y1 = y0 + PX
            x = 0
            while x < len(r):
                if r[x] == "#":
                    x0 = x
                    while x < len(r) and r[x] == "#":
                        x += 1
                    # Contorno en sentido horario (exterior en TrueType).
                    pen.moveTo((x0 * PX, y0))
                    pen.lineTo((x0 * PX, y1))
                    pen.lineTo((x * PX, y1))
                    pen.lineTo((x * PX, y0))
                    pen.closePath()
                else:
                    x += 1
        glyphs[name] = pen.glyph()
        metrics[name] = ((w + 1) * PX, 0)
        order.append(name)
        cmap[ord(ch)] = name

    fb = FontBuilder(8 * PX, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=8 * PX, descent=-2 * PX)
    fb.setupNameTable({"familyName": "Subterra Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=8 * PX, sTypoDescender=-2 * PX, sTypoLineGap=0,
                usWinAscent=8 * PX, usWinDescent=2 * PX)
    fb.setupPost()
    fb.save(OUT)
    print("glifos:", len(G), "->", OUT)


if __name__ == "__main__":
    build()
